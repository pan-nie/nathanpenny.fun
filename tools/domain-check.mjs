#!/usr/bin/env node
// Refuse to let a stale hostname or address survive in the repository.
//
//   node tools/domain-check.mjs
//
// Four things are checked, in order of how badly they bite:
//
//   1. `applied` must equal `hosts`/`emails` — otherwise someone edited
//      site.config.json and did not run `node tools/domain-sync.mjs`, and the
//      site is still serving the old domain while the config claims otherwise.
//   2. No tracked file may contain a hostname that `hostRewrites` /
//      `emailRewrites` (or a derived pair) retired. This is the check that
//      catches "I updated 39 files and forgot the fortieth". An occurrence
//      inside an address is a warning, not a failure: the mail domain is a
//      separate decision from the site domain.
//   3. Same for every `legacyApexDomains` entry, in every spelling — bare apex,
//      subdomain, `*.apex` wildcard. A full-hostname-only scan misses those.
//   4. Binary files (the CV PDF/DOCX) are scanned too, but only warned about:
//      they have to be regenerated by hand, so failing the build would block the
//      fix rather than prompt it.
//
// Wired into .github/workflows/domain-check.yml.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  CONFIG_NAME, ROOT, collectFiles, loadConfig, pendingConfigChange,
  planRewrites, scanHosts, scanLegacyApex, validateConfig,
} from './domain-lib.mjs';

const failures = [];
const warnings = [];

const config = loadConfig();

const problems = validateConfig(config);
if (problems.length) failures.push({ label: CONFIG_NAME + ' is not usable', detail: problems });

const pending = pendingConfigChange(config);
if (pending.length) {
  failures.push({
    label: 'site.config.json was edited without running the sync',
    detail: [...pending, 'run: node tools/domain-sync.mjs'],
  });
}

const { hostPairs, emailPairs } = planRewrites(config);
const retiredHosts = [...hostPairs.keys()].filter(key => !key.includes('\\'));
const retiredEscaped = [...hostPairs.keys()].filter(key => key.includes('\\'));
const retiredEmails = [...emailPairs.keys()];
const legacyApexes = config.legacyApexDomains || [];

const files = collectFiles();
const read = rel => readFileSync(join(ROOT, rel), files.text.includes(rel) ? 'utf8' : 'latin1');

const hostHits = [];
const hostHitKeys = new Set();
const addressHits = new Set();
const manualHits = [];
const addHost = (rel, entry) => {
  // A subdomain also matches the bare apex, so the same line can be reported by
  // two guards; one line should be one finding.
  const key = `${rel}:${entry.line}`;
  if (hostHitKeys.has(key)) return;
  hostHitKeys.add(key);
  hostHits.push(`  ${rel}:${entry.line}  ${entry.text}`);
};
const addAddress = (rel, entry) => addressHits.add(`${rel}:${entry.line}  ${entry.needle}  ${entry.text}`);

for (const rel of files.text) {
  const text = read(rel);

  const { host, address } = scanHosts(text, [...retiredHosts, ...retiredEscaped]);
  for (const entry of host) addHost(rel, entry);
  for (const entry of address) addAddress(rel, entry);

  if (retiredEmails.length) {
    for (const entry of scanHosts(text, retiredEmails).host) addHost(rel, entry);
  }

  if (legacyApexes.length) {
    const legacy = scanLegacyApex(text, legacyApexes);
    for (const entry of legacy.host) addHost(rel, entry);
    for (const entry of legacy.address) addAddress(rel, entry);
  }
}

if (hostHits.length) {
  failures.push({
    label: 'retired hosts/addresses are still in the tree',
    detail: [...hostHits, 'run: node tools/domain-sync.mjs'],
  });
}

for (const rel of files.binary) {
  const raw = read(rel);
  const hits = scanHosts(raw, [...retiredHosts, ...retiredEscaped, ...retiredEmails]).host;
  const legacy = legacyApexes.length ? scanLegacyApex(raw, legacyApexes).host : [];
  if (hits.length || legacy.length) {
    manualHits.push(`  ${rel}  (${hits.length + legacy.length} hit(s))`);
  }
}

for (const entry of addressHits) {
  warnings.push(`address on a retired domain — keep it only if you mean to: ${entry}`);
}
for (const entry of manualHits) {
  warnings.push(`regenerate by hand, it cannot be rewritten here: ${entry}`);
}

for (const warning of warnings) console.warn('warning: ' + warning);

if (failures.length) {
  for (const failure of failures) {
    console.error('\n✗ ' + failure.label);
    for (const line of failure.detail) console.error(line);
  }
  if (legacyApexes.length) {
    console.error('\nIf an entry in legacyApexDomains is still a domain you own and serve,');
    console.error('delete it there — this list means "must not appear anywhere".');
  }
  console.error(`\ndomain check failed (${failures.length} problem${failures.length === 1 ? '' : 's'}).`);
  process.exit(1);
}

console.log('✓ domain check passed');
console.log('  hosts:  ' + Object.entries(config.hosts || {}).map(([r, h]) => `${r}=${h}`).join('  '));
console.log('  emails: ' + Object.values(config.emails || {}).join('  '));
console.log(`  scanned ${files.text.length} text + ${files.binary.length} binary files; guarding ` +
  `${hostPairs.size} hostname spelling${hostPairs.size === 1 ? '' : 's'}, ` +
  `${retiredEmails.length} address${retiredEmails.length === 1 ? '' : 'es'}, ` +
  `${legacyApexes.length} abandoned apex domain${legacyApexes.length === 1 ? '' : 's'}`);
